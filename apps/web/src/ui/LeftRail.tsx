export function LeftRail() {
  const t = useT();
  const tab = useStore((s) => s.leftTab);
  const setTab = useStore((s) => s.setLeftTab);
  const me = useStore((s) => s.me);
  const view = useStore((s) => (me ? s.views[me.sessionWorldId] : undefined));
  const contacts = view?.actors.filter((a) => a.contact && a.id !== "wren") ?? [];
  return (
    <aside className="rail rail-left glass" aria-label="Network">
      <div className="rail-head">
        <div className="tabs" role="tablist">
          {(["feed", "contacts", "crew"] as const).map((k) => (
            <button key={k} role="tab" aria-selected={tab === k} onClick={() => setTab(k)}>
              {t(k === "feed" ? "Feed" : k === "contacts" ? "Contacts" : "Crew")}
              {k === "contacts" && contacts.length > 0 && <span className="count">{contacts.length}</span>}
            </button>
          ))}
        </div>
        <RailCollapse side="left" />
      </div>
      <div className="rail-body" role="tabpanel">
        {tab === "feed" && <Feed />}
        {tab === "contacts" && <Contacts actors={contacts} />}
        {tab === "crew" && <Crew />}
      </div>
    </aside>
  );
}

export function Feed() {
  const t = useT();
  const me = useStore((s) => s.me);
  const scenario = useStore((s) => s.scenario);
  const [scope, setScope] = useState<"night" | "shared">("night");
  const worldId = me ? (scope === "night" ? me.sessionWorldId : me.sharedWorldId) : null;
  const events = useStore((s) => (worldId ? s.events[worldId] : undefined)) ?? [];
  const name = (id: string) => scenario?.cast.find((c) => c.id === id)?.name ?? id;
  const shown = events.filter((e) => e.type === "post.published" || e.type === "message.sent" || SYSTEM_LABELS[e.type]).slice(-120).reverse();
  return (
    <div>
      <div className="feed-scope">
        <button className="toggle" aria-pressed={scope === "night"} onClick={() => setScope("night")}>{t("Your night")}</button>
        <button className="toggle" aria-pressed={scope === "shared"} onClick={() => setScope("shared")}>{t("Shared city")}</button>
      </div>
      {scope === "shared" && <p className="notice accent">Everyone's shared simulation. Posts here are generated by the VICEPULSE server, not GTA telemetry or real people.</p>}
      {!shown.length && <div className="empty">Quiet so far. The city is warming up…</div>}
      {shown.map((e) => <FeedItem key={e.id} e={e} name={name} worldId={worldId!} />)}
    </div>
  );
}

function FeedItem({ e, name, worldId }: { e: WorldEvent; name: (id: string) => string; worldId: string }) {
  const t = useT();
  const [chain, setChain] = useState<any[] | null>(null);
  const isPost = e.type === "post.published", isMsg = e.type === "message.sent";
  const author = isPost ? e.payload.authorId : isMsg ? e.payload.fromId : null;
  const priv = e.visibility !== "public";
  const why = async () => {
    if (chain) { setChain(null); return; }
    try { setChain((await api<{ chain: any[] }>(`/api/worlds/${worldId}/events/${e.id}/chain`)).chain); } catch { setChain([]); }
  };
  if (!author) {
    return (
      <div className={`feed-item ${priv ? "private" : ""}`}>
        <div className="feed-head"><span className="avatar" style={{ background: "rgba(255, 255, 255, 0.12)", color: "var(--text-2)" }}>·</span><span className="muted">{SYSTEM_LABELS[e.type]?.(e.payload, name) ?? e.type}</span><span className="when">{clock(e.simTime)}</span></div>
        {e.causeEventId && <div className="feed-meta"><button onClick={why}>{t("Why?")}</button></div>}
        {chain && <Chain chain={chain} name={name} />}
      </div>
    );
  }
  return (
    <div className={`feed-item ${priv ? "private" : ""}`}>
      <div className="feed-head">
        <span className="avatar" style={{ background: ACTOR_COLORS[author] ?? "#FFF8F2" }}>{name(author)[0]}</span>
        <span className="who">{name(author)}</span>
        <span className="dim" style={{ fontSize: 11 }}>{isMsg ? "→ you" : e.payload.kind === "rumor" ? "rumour" : e.payload.kind}</span>
        <span className="when">{clock(e.simTime)}</span>
      </div>
      <p className="feed-text">{e.payload.text}</p>
      <div className="feed-meta">
        <span>#{e.sequence}</span>
        {e.payload.narrativeSource && !["deterministic", "rule_based", "cache"].includes(e.payload.narrativeSource) && <span title="Wording from the optional narrative model; facts are validated by the server">✦ {e.payload.narrativeSource}</span>}
        {e.causeEventId && <button onClick={why}>{t("Why?")}</button>}
      </div>
      {chain && <Chain chain={chain} name={name} />}
    </div>
  );
}

function Chain({ chain, name }: { chain: any[]; name: (id: string) => string }) {
  if (!chain.length) return <ul className="chain"><li>No recorded cause.</li></ul>;
  return (
    <ul className="chain">
      {chain.map((c) => (
        <li key={c.id}>
          <b>#{c.sequence} {clock(c.simTime)}</b>{" "}
          {c.type === "undisclosed" ? <em>{c.note}</em>
            : c.type === "world.observed" ? `${name(c.actorIds?.[0] ?? "")} saw something`
            : SYSTEM_LABELS[c.type]?.(c.payload, name) ?? (c.payload?.text ? `“${c.payload.text}”` : c.type.replace(/[._]/g, " "))}
          {c.revealed && <span className="warn"> (revealed after the fact)</span>}
        </li>
      ))}
    </ul>
  );
}

function TrustBar({ value }: { value: number }) {
  return (
    <span className="trust" aria-label={`Trust ${value}`}>
      {[-3, -2, -1, 1, 2, 3].map((v) => <i key={v} className={v < 0 ? (value <= v ? "neg" : "") : value >= v ? "on" : ""} />)}
    </span>
  );
}

function Contacts({ actors }: { actors: ActorView[] }) {
  const me = useStore((s) => s.me);
  const view = useStore((s) => (me ? s.views[me.sessionWorldId] : undefined));
  if (!actors.length) return <div className="empty">No contacts yet. Investigate Vega's lead to meet people.</div>;
  return (
    <div>
      {actors.map((a) => {
        const act = view?.agentActions.find((x) => x.command === "contact" && x.target === a.id);
        return (
          <div key={a.id} className="contact">
            <span className="avatar" style={{ background: ACTOR_COLORS[a.id] ?? "#FFF8F2" }}>{a.name[0]}</span>
            <div className="meta">
              <div className="name">{a.name}</div>
              <div className="role">{a.role}</div>
              <div className="task">{a.task}</div>
              {a.trust && <div className="row" style={{ gap: 6 }}><TrustBar value={a.trust.value} /><span className="dim" style={{ fontSize: 11 }}>{a.trust.label}</span></div>}
              {a.debts.filter((d) => !d.resolved).map((d, i) => <div key={i} className="warn" style={{ fontSize: 12 }}>Owes {d.to} ${d.amount}</div>)}
              {act && (
                <button className="btn" style={{ marginTop: 6, padding: "4px 10px" }} disabled={!act.enabled} title={act.reason} onClick={() => agentCommand({ command: "contact", actorId: a.id })}>
                  {act.enabled ? "Message" : act.reason}
                </button>
              )}
            </div>
          </div>
        );
      })}
    </div>
  );
}

export function Crew() {
  const t = useT();
  const me = useStore((s) => s.me);
  const view = useStore((s) => (me ? s.views[me.sessionWorldId] : undefined));
  const scenario = useStore((s) => s.scenario);
  const flyTo = useStore((s) => s.flyTo);
  const [dest, setDest] = useState("");
  const wren = view?.actors.find((a) => a.id === "wren");
  if (!view || !wren) return <div className="empty">Loading your crew…</div>;
  const travel = view.agentActions.find((a) => a.command === "travel");
  return (
    <div className="stack">
      <div className="contact" style={{ borderBottom: 0 }}>
        <span className="avatar" style={{ background: ACTOR_COLORS.wren }}>W</span>
        <div className="meta">
          <div className="name">Wren <span className="dim">· {t("Your agent")}</span></div>
          <div className="role">{wren.role}</div>
          <div className="task">{wren.task}</div>
        </div>
        <button className="icon-btn" onClick={() => flyTo(wren.pos[0], wren.pos[1], 2500)} title="Show on map">Locate</button>
      </div>
      {view.resources && (
        <div className="row">
          <span className="chip">Cash <strong>${view.resources.cash}</strong></span>
          <span className="chip">Favours <strong>{view.resources.favors}</strong></span>
        </div>
      )}
      <h3 className="h-sec">Orders</h3>
      <div className="action-list">
        {view.agentActions.filter((a) => a.command !== "contact" && a.command !== "travel").map((a) => (
          <button key={a.command} className="action" disabled={!a.enabled} onClick={() => agentCommand({ command: a.command })}>
            <span className="lbl">{a.label}{!a.enabled && a.reason && <span className="why">{a.reason}</span>}</span>
          </button>
        ))}
      </div>
      {travel && (
        <div className="row" style={{ marginTop: 4 }}>
          <select className="input" style={{ flex: 1 }} value={dest} onChange={(e) => setDest(e.target.value)} disabled={!travel.enabled} aria-label="Destination">
            <option value="">Travel to…</option>
            {scenario?.places.map((p) => <option key={p.id} value={p.node}>{p.name}</option>)}
          </select>
          <button className="btn" disabled={!travel.enabled || !dest} title={travel.reason} onClick={() => agentCommand({ command: "travel", nodeId: dest })}>Go</button>
        </div>
      )}
      <h3 className="h-sec">What Wren knows</h3>
      {view.facts.length ? view.facts.map((f) => <p key={f.key} style={{ margin: "0 0 6px", fontSize: 12.5 }}><span className="mono dim">{f.learnedAt}</span> {f.text}</p>) : <div className="dim">Nothing yet.</div>}
      {view.history.length > 0 && (
        <>
          <h3 className="h-sec">Past runs</h3>
          {view.history.map((h, i) => <div key={i} className="mono" style={{ fontSize: 11.5 }}>{h.missionId}: {h.outcome}{h.leaked ? " · leaked" : ""}</div>)}
        </>
      )}
    </div>
  );
}
